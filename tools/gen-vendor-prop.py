#!/usr/bin/env python3
"""Generate vendor.prop for tcl/boratf from the stock UHBG vendor build.prop.

Input:  tools/stock/vendor-build.prop (copy of the stock /vendor/build.prop)
Output: ../vendor.prop
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.environ.get(
    "BORATF_VENDOR_BUILD_PROP", os.path.join(HERE, "stock", "vendor-build.prop")
)
OUT = os.environ.get(
    "BORATF_VENDOR_PROP_OUT", os.path.normpath(os.path.join(HERE, "..", "vendor.prop"))
)

EXCLUDE = [
    # persist.log.tag.* is owned by hardware/mediatek/configs/properties/
    # vendor_logtag.mk (included from device.mk); shipping the stock values
    # too would be a duplicate assignment with different values.
    r"^persist\.log\.tag\.",
    r"^ro\.product\.vendor\.",
    r"^ro\.vendor\.build\.",
    r"^ro\.odm\.build\.",
    r"^ro\.vndk\.version=",
    r"^ro\.bionic\.",
    r"^ro\.zygote=",
    r"^ro\.product\.first_api_level=",
    r"^ro\.board\.first_api_level=",
    r"^ro\.boot\.dynamic_partitions=",
    r"^ro\.apex\.updatable=",
    r"^ro\.control_privapp_permissions=",
    r"^ro\.facebook\.partnerid=",
    r"^ro\.product\.property_source_order=",
    r"^ro\.product\.board=",
    r"^ro\.board\.platform=",
    r"^ro\.vendor\.product\.cpu\.abilist",
    r"^ro\.minui\.pixel_format=",
    r"^ro\.vendor\.rc=",
    r"^persist\.sys\.dalvik\.vm\.lib\.2=",
    r"^dalvik\.vm\.isa\.",
    r"^dalvik\.vm\.heap",
]

HEADER = """#
# SPDX-FileCopyrightText: The LineageOS Project
# SPDX-License-Identifier: Apache-2.0
#
# Functional properties from the stock TCL UHBG vendor image.
# Build identity properties are intentionally omitted (the build provides
# ro.vendor.build.*, ro.product.vendor.*, ro.vndk.version, ro.bionic.*, ...).
#
# Generated by tools/gen-vendor-prop.py; do not edit by hand.
#
"""


def main():
    props = {}
    with open(SRC) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, val = line.split("=", 1)
            if any(re.match(rx, line) for rx in EXCLUDE):
                continue
            props[key] = val  # last wins

    # keep persist.log.tag.* grouped at the end
    normal = {k: v for k, v in props.items() if not k.startswith("persist.log.tag.")}
    logtags = {k: v for k, v in props.items() if k.startswith("persist.log.tag.")}

    out = [HEADER]
    for k in sorted(normal):
        out.append(f"{k}={normal[k]}")
    if logtags:
        out.append("")
        out.append("# MTK log tags")
        for k in sorted(logtags):
            out.append(f"{k}={logtags[k]}")
    out.append("")

    with open(OUT, "w") as f:
        f.write("\n".join(out))

    print(f"{len(normal)} props + {len(logtags)} log tags -> {OUT}")


if __name__ == "__main__":
    main()
