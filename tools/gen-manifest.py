#!/usr/bin/env python3
"""Generate the device manifest for tcl/boratf from the stock vendor manifest.

Input:  tools/stock/vintf-manifest.xml (copy of the stock
        /vendor/etc/vintf/manifest.xml)
Output: ../manifest.xml

HALs that are rebuilt from source (and therefore ship their own vintf
fragments) are dropped, as are stock entries that no longer have a service
in this ROM; the HALs kept as stock blobs stay. The rebuilt audio service
registers both 7.1 and 7.0, so a 7.1 entry is added.
"""
import copy
import os
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.environ.get(
    "BORATF_STOCK_MANIFEST", os.path.join(HERE, "stock", "vintf-manifest.xml")
)
OUT = os.environ.get(
    "BORATF_MANIFEST_OUT", os.path.normpath(os.path.join(HERE, "..", "manifest.xml"))
)

# HALs rebuilt from source (services install their own vintf fragments)
DROP = {
    "android.hardware.bluetooth",  # AIDL service (hardware/mediatek)
    "android.hardware.memtrack",  # AIDL service (hardware/mediatek)
    "android.hardware.sensors",  # AIDL multihal + HIDL 2.0 subhal
    "android.hardware.thermal",  # AIDL service (hardware/mediatek)
    "vendor.mediatek.hardware.mtkpower",  # AIDL stub (hardware/mediatek)

    # Dead stock HIDL entries: no service/impl is shipped for them.
    # android.hardware.bluetooth.audio: HIDL 2.1 is replaced by the AIDL
    # interface (android.hardware.bluetooth.audio-impl ships the AIDL vintf
    # fragment and the MTK audio service registers the provider factory).
    "android.hardware.bluetooth.audio",
    # android.hardware.media.omx: the OMX service binary is not shipped; the
    # MTK codecs are served by the C2 HAL (media_codecs_c2.xml).
    "android.hardware.media.omx",
    # vendor.mediatek.hardware.bluetooth.audio: served by the stock MTK HIDL
    # blobs but unused by the AOSP Bluetooth stack (AIDL providers only).
    # The blobs stay until the AIDL path is validated on-device.
    "vendor.mediatek.hardware.bluetooth.audio",
}

HEADER = """<!--
     SPDX-FileCopyrightText: The LineageOS Project
     SPDX-License-Identifier: Apache-2.0

     Device manifest for the TCL Ion V T607DL (boratf).
     Derived from the stock UHBG vendor manifest: HALs that are rebuilt from
     source are removed (their services install vintf fragments), the rest of
     the stock blob HALs are kept.

     Generated by tools/gen-manifest.py; do not edit by hand.
-->
"""


def main():
    tree = ET.parse(SRC)
    root = tree.getroot()
    root.set("target-level", "7")

    dropped = []
    audio_hal = None
    for hal in list(root):
        if hal.tag in ("sepolicy", "kernel"):
            root.remove(hal)
            continue
        if hal.tag == "hal":
            name = hal.findtext("name")
            if name in DROP:
                dropped.append(name)
                root.remove(hal)
                continue
            if name == "android.hardware.audio":
                audio_hal = hal

    # The rebuilt service registers both 7.1 and 7.0. VINTF allows only one
    # hal entry per HAL name, so extend the existing audio entry with an
    # additional version/fqname (same shape as the stock thermal 1.0/2.0
    # entry) instead of adding a second hal element.
    assert audio_hal is not None

    version70 = audio_hal.find("version")
    assert version70 is not None
    version71 = copy.deepcopy(version70)
    version71.text = "7.1"
    audio_hal.insert(list(audio_hal).index(version70) + 1, version71)

    fqname70 = audio_hal.find("fqname")
    assert fqname70 is not None
    fqname71 = copy.deepcopy(fqname70)
    fqname71.text = "@7.1::IDevicesFactory/default"
    audio_hal.insert(list(audio_hal).index(fqname70) + 1, fqname71)

    ET.indent(root, space="    ")
    body = ET.tostring(root, encoding="unicode")

    with open(OUT, "w") as f:
        f.write(HEADER)
        f.write(body)
        f.write("\n")

    print("dropped:", dropped)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
